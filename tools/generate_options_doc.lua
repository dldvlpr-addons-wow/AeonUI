-- tools/generate_options_doc.lua
-- Référence des réglages, tirée de la fenêtre d'options elle-même : jamais en retard sur le code.
--   lua tools/generate_options_doc.lua [frFR|enUS] > docs/options.md   (depuis la racine du dépôt)
-- Charge l'addon hors du jeu (mêmes simulations que tests/run_tests.lua), écoute chaque widget
-- posé par les pages puis écrit une page Markdown : page > onglet > section > réglage, avec son
-- type, sa valeur par défaut (profil neuf), ses bornes et son infobulle.

