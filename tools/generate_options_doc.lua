Mock.locale = arg[1] or "frFR"

local NS = {}
local entriesByLayout = setmetatable({}, { __mode = "k" })

--- Enregistre chaque appel de widget d'un layout, dans l'ordre de la page.
local function ListenToLayouts()
    local Layout = getmetatable(NS.Widgets.NewLayout(CreateFrame("Frame")))
    local function record(layout, entry)
        local list = entriesByLayout[layout] or {}
        entriesByLayout[layout] = list
        entry.tab = layout.currentTab and layout.tabs[layout.currentTab].label
        list[#list + 1] = entry
        return entry
    end
    local function wrap(method, describe)
        local original = Layout[method]
        Layout[method] = function(self, ...)
            local result = original(self, ...)
            local entry = describe(...)
            if entry then
                entry.kind = entry.kind or method
                self.lastDocEntry = record(self, entry)
            end
            return result
        end
    end
    wrap("Title", function(text) return { text = text } end)
    wrap("Note", function(text, indent) return { text = text, indent = indent } end)
    wrap("Check", function(label, get, _, indent) return { text = label, get = get, indent = indent } end)
    wrap("Slider", function(label, minValue, maxValue, step, get, _, indent, format)
        return { text = label, get = get, indent = indent, min = minValue, max = maxValue, step = step, format = format }
    end)
    wrap("Dropdown", function(label, choices, get, _, indent)
        return { text = label, choices = choices, get = get, indent = indent }
    end)
    wrap("Color", function(label, get, _, indent) return { text = label, get = get, indent = indent } end)
    wrap("Button", function(label, _, indent) return { text = label, indent = indent } end)
    wrap("EditBox", function(label, _, _, _, indent) return { text = label, indent = indent } end)
    -- L'infobulle se rattache au dernier widget posé.
    local hint = Layout.Hint
    Layout.Hint = function(self, text)
        if self.lastDocEntry and text then self.lastDocEntry.hint = text end
        return hint(self, text)
    end
end

for raw in io.lines("AeonUI.toc") do
